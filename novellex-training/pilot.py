"""Public NovelLex GLiNER2.5 LoRA CPU smoke test: synthetic examples only."""
import argparse
from collections import Counter, defaultdict
import gzip
import hashlib
import json
from pathlib import Path
import random
import time

ROOT = Path(__file__).resolve().parent
SEED = ROOT / 'synthetic_seed_v01.jsonl.gz'
MODEL = 'fastino/gliner2.5-small-v1'
LABELS = {'CHARACTER':'fictional person', 'LOCATION':'named fictional place',
          'ARTIFACT':'named magical artifact', 'TECHNIQUE':'named fantasy technique',
          'ORGANIZATION':'named fictional organization', 'CONCEPT':'named fictional world concept',
          'RANK':'named rank', 'TITLE':'personal title'}


def prepare(out):
    raw = gzip.decompress(SEED.read_bytes())
    records = [json.loads(x) for x in raw.decode('utf-8').splitlines() if x.strip()]
    assert len(records) == 134
    assert len({r['id'] for r in records}) == 134
    assert {r['source'] for r in records} == {'original_synthetic_fantasy'}
    assert {r['language'] for r in records} == {'en'}
    for r in records:
        for e in r['entities']:
            assert e['label'] in LABELS
            assert 0 <= e['start'] < e['end'] <= len(r['text'])
            assert r['text'][e['start']:e['end']] == e['text']
    pairs = [records[i:i+2] for i in range(0, 134, 2)]
    random.Random(20261110).shuffle(pairs)
    valid, train = [r for p in pairs[:13] for r in p], [r for p in pairs[13:] for r in p]
    assert len(train) == 108 and len(valid) == 26
    assert not {r['id'] for r in train} & {r['id'] for r in valid}

    def convert(rows):
        for r in rows:
            entities = defaultdict(list)
            for e in r['entities']:
                name = LABELS[e['label']]
                if e['text'] not in entities[name]:
                    entities[name].append(e['text'])
            yield {'input':r['text'], 'output':{'entities':dict(entities)}}

    for label, rows in [('train',train), ('validation',valid)]:
        (out / f'{label}.jsonl').write_text(''.join(json.dumps(x,ensure_ascii=False)+'\n'
                                            for x in convert(rows)),encoding='utf-8')
    meta = {'synthetic_only':True,'source_sha256':hashlib.sha256(raw).hexdigest(),
            'examples':len(records),'spans':sum(len(r['entities']) for r in records),
            'train':len(train),'validation':len(valid),
            'warning':'Not a real-novel benchmark; labels generated by an AI teacher.'}
    assert meta['source_sha256'] == '66c016c37e6b8c2b36c88b2eb3ac7768d6e96a2d7d63d94bb503466648dca6ff'
    assert meta['spans'] == 128
    (out/'data_checks.json').write_text(json.dumps(meta,indent=2))
    print('DATA_CHECKS',json.dumps(meta),flush=True)
    return meta


def train(out, steps):
    meta = prepare(out)
    import torch
    from gliner2 import AutoExtractor
    from gliner2.training.trainer import ExtractorTrainer, TrainingConfig
    torch.set_num_threads(4)
    t0 = time.monotonic()
    model = AutoExtractor.from_pretrained(MODEL)
    settings = TrainingConfig(output_dir=str(out/'checkpoints'),num_epochs=1,
        max_steps=steps,batch_size=2,encoder_lr=1e-5,task_lr=1e-4,
        fp16=False,bf16=False,num_workers=0,pin_memory=False,
        fused_optimizer=False,eval_strategy='no',save_best=False,
        logging_steps=1,report_to_wandb=False,seed=20261110,
        use_lora=True,lora_r=8,lora_alpha=16.0,
        lora_target_modules=['encoder','all_task_heads'],save_adapter_only=True)
    trainer = ExtractorTrainer(model,settings)
    summary = trainer.train(train_data=str(out/'train.jsonl'))
    checkpoint = out/'checkpoints'/'final'
    files = [p.name for p in checkpoint.rglob('*') if p.is_file()]
    assert any(n.endswith(('.safetensors','.bin')) for n in files), 'No trained model checkpoint'
    report = {'status':'trained_pilot','model':MODEL,'steps_requested':steps,
              'seconds':round(time.monotonic()-t0,2),'checkpoint_files':files,
              'train_summary':summary,'data':meta,
              'caveat':'Only synthetic smoke training; real-novel accuracy unverified.'}
    (out/'training_report.json').write_text(json.dumps(report,default=str,indent=2))
    print('TRAINING_FINISHED_WITH_CHECKPOINT',json.dumps({k:report[k] for k in
          ('status','steps_requested','seconds','checkpoint_files')}),flush=True)


if __name__ == '__main__':
    p=argparse.ArgumentParser()
    p.add_argument('mode',choices=('validate','train'))
    p.add_argument('--output',default='novellex_output')
    p.add_argument('--max-steps',type=int,default=8)
    args=p.parse_args()
    assert 1 <= args.max_steps <= 64
    path=Path(args.output);path.mkdir(parents=True,exist_ok=True)
    if args.mode == 'validate':prepare(path)
    else:train(path,args.max_steps)
